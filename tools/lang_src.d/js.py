"""Browser scripts

Every string a script in assets/js/ shows to a person. The page carries these — and ONLY these —
as a JSON bundle (langJsBridge() in includes/lang.php) and t() in assets/js/i18n.js reads them.
Keys are `js.<area>.<slug>`; the area is the script the string lives in (wl, users, index, settings,
common, app, ...). A template string a script also needs is repeated here under `js.` rather than
widening the bundle to the whole dictionary.
"""

S = {}


def add(prefix, pairs):
    for k, v in pairs.items():
        key = prefix + '.' + k if prefix else k
        assert key not in S, 'duplicate key ' + key
        assert isinstance(v, tuple) and len(v) == 2, key
        S[key] = v


