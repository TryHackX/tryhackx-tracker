"""API messages and the maintenance page

Sentences the PHP side sends to a person's browser: JSON error/message strings of the endpoints in
api/, warnings assembled in includes/, and the static maintenance page shown when the database is
not answering. Keys are api.<area>.<slug>; the English value is the exact former literal, because
the tests compare messages and __() returns English in CLI code.
"""

S = {}


def add(prefix, pairs):
    for k, v in pairs.items():
        key = prefix + '.' + k if prefix else k
        assert key not in S, 'duplicate key ' + key
        assert isinstance(v, tuple) and len(v) == 2, key
        S[key] = v


